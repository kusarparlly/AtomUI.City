namespace AtomUI.City.Mvvm;

/// <summary>
/// Defines the supported operation status values.
/// </summary>
public enum OperationStatus
{
    /// <summary>
    /// Represents the completed value.
    /// </summary>
    Completed,
    /// <summary>
    /// Represents the failed value.
    /// </summary>
    Failed,
    /// <summary>
    /// Represents the canceled value.
    /// </summary>
    Canceled,
    /// <summary>
    /// Represents the rejected value.
    /// </summary>
    Rejected,
    /// <summary>
    /// Represents the running value.
    /// </summary>
    Running,
}
