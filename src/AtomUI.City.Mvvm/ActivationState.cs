namespace AtomUI.City.Mvvm;

/// <summary>
/// Defines the supported activation state values.
/// </summary>
public enum ActivationState
{
    /// <summary>
    /// Represents the constructed value.
    /// </summary>
    Constructed,
    /// <summary>
    /// Represents the activating value.
    /// </summary>
    Activating,
    /// <summary>
    /// Represents the active value.
    /// </summary>
    Active,
    /// <summary>
    /// Represents the deactivating value.
    /// </summary>
    Deactivating,
    /// <summary>
    /// Represents the deactivated value.
    /// </summary>
    Deactivated,
    /// <summary>
    /// Represents the disposed value.
    /// </summary>
    Disposed,
}
