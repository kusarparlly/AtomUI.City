namespace AtomUI.City.Mvvm;

/// <summary>
/// Defines the supported interaction result status values.
/// </summary>
public enum InteractionResultStatus
{
    /// <summary>
    /// Represents the completed value.
    /// </summary>
    Completed,
    /// <summary>
    /// Represents the canceled value.
    /// </summary>
    Canceled,
    /// <summary>
    /// Represents the failed value.
    /// </summary>
    Failed,
    /// <summary>
    /// Represents the not handled value.
    /// </summary>
    NotHandled,
}
