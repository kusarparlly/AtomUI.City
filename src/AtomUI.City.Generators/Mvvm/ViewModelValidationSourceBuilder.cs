using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.City.Generators.Mvvm;

internal static class ViewModelValidationSourceBuilder
{
    public static string Build(ViewModelValidationMetadata metadata)
    {
        if (metadata is null)
        {
            throw new ArgumentNullException(nameof(metadata));
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        var namespaceName = metadata.Type.ContainingNamespace.IsGlobalNamespace
            ? null
            : metadata.Type.ContainingNamespace.ToDisplayString();
        if (namespaceName is not null)
        {
            builder.Append("namespace ").Append(namespaceName).AppendLine(";");
            builder.AppendLine();
        }

        builder.Append("partial class ").Append(EscapeIdentifier(metadata.Type.Name)).AppendLine();
        builder.AppendLine("{");
        AppendPropertyDispatcher(builder, metadata);
        builder.AppendLine();
        AppendFullValidation(builder, metadata);
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendPropertyDispatcher(
        StringBuilder builder,
        ViewModelValidationMetadata metadata)
    {
        builder.AppendLine("    protected override void ValidateGeneratedProperty(");
        builder.AppendLine("        string propertyName,");
        builder.AppendLine("        object? value,");
        builder.AppendLine("        global::System.Collections.Generic.ICollection<string> errors)");
        builder.AppendLine("    {");
        builder.AppendLine("        switch (propertyName)");
        builder.AppendLine("        {");

        foreach (var property in metadata.Properties)
        {
            builder.Append("            case nameof(").Append(EscapeIdentifier(property.Property.Name)).AppendLine("):");
            foreach (var rule in property.Rules)
            {
                AppendRule(builder, property.Property, rule);
            }
            builder.AppendLine("                break;");
        }

        builder.AppendLine("            default:");
        builder.AppendLine("                base.ValidateGeneratedProperty(propertyName, value, errors);");
        builder.AppendLine("                break;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void AppendRule(
        StringBuilder builder,
        IPropertySymbol property,
        ViewModelValidationRule rule)
    {
        switch (rule.Kind)
        {
            case ViewModelValidationRuleKind.Attribute:
                builder.Append("                ValidateAttribute(errors, value, nameof(")
                    .Append(EscapeIdentifier(property.Name)).Append("), ")
                    .Append(CreateAttributeExpression(rule.Attribute)).AppendLine(");");
                break;
            case ViewModelValidationRuleKind.Compare:
                builder.Append("                if (!global::System.Object.Equals(this.")
                    .Append(EscapeIdentifier(property.Name)).Append(", this.")
                    .Append(EscapeIdentifier(rule.ComparedProperty!.Name)).AppendLine("))");
                builder.AppendLine("                {");
                builder.Append("                    errors.Add(")
                    .Append(CreateAttributeExpression(rule.Attribute)).Append(".FormatErrorMessage(nameof(")
                    .Append(EscapeIdentifier(property.Name)).AppendLine(")));");
                builder.AppendLine("                }");
                break;
            case ViewModelValidationRuleKind.CustomValidation:
                var method = rule.CustomMethod!;
                builder.Append("                ValidateResult(errors, ")
                    .Append(method.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                    .Append('.').Append(EscapeIdentifier(method.Name)).Append("(this.")
                    .Append(EscapeIdentifier(property.Name));
                if (method.Parameters.Length == 2)
                {
                    builder.Append(", new global::System.ComponentModel.DataAnnotations.ValidationContext(this)")
                        .Append(" { MemberName = nameof(").Append(EscapeIdentifier(property.Name))
                        .Append("), DisplayName = nameof(").Append(EscapeIdentifier(property.Name)).Append(") }");
                }
                builder.AppendLine("));");
                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(rule), rule.Kind, "Unknown validation rule kind.");
        }
    }

    private static void AppendFullValidation(
        StringBuilder builder,
        ViewModelValidationMetadata metadata)
    {
        builder.AppendLine("    protected override void ValidateAllGeneratedProperties()");
        builder.AppendLine("    {");
        foreach (var property in metadata.Properties)
        {
            builder.Append("        ValidateProperty(nameof(").Append(EscapeIdentifier(property.Property.Name))
                .Append("), this.").Append(EscapeIdentifier(property.Property.Name)).AppendLine(");");
        }
        builder.AppendLine("    }");
    }

    private static string CreateAttributeExpression(AttributeData attribute)
    {
        var builder = new StringBuilder("new ");
        builder.Append(attribute.AttributeClass!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
        builder.Append('(');
        for (var index = 0; index < attribute.ConstructorArguments.Length; index++)
        {
            if (index > 0)
            {
                builder.Append(", ");
            }
            builder.Append(RenderConstant(attribute.ConstructorArguments[index]));
        }
        builder.Append(')');

        if (attribute.NamedArguments.Length > 0)
        {
            builder.Append(" { ");
            for (var index = 0; index < attribute.NamedArguments.Length; index++)
            {
                if (index > 0)
                {
                    builder.Append(", ");
                }
                builder.Append(EscapeIdentifier(attribute.NamedArguments[index].Key)).Append(" = ")
                    .Append(RenderConstant(attribute.NamedArguments[index].Value));
            }
            builder.Append(" }");
        }

        return builder.ToString();
    }

    private static string RenderConstant(TypedConstant constant)
    {
        if (constant.IsNull)
        {
            return "null";
        }
        if (constant.Kind == TypedConstantKind.Type && constant.Value is ITypeSymbol type)
        {
            return $"typeof({type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})";
        }
        if (constant.Kind == TypedConstantKind.Enum)
        {
            return $"({constant.Type!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}){RenderPrimitive(constant.Value!)}";
        }
        if (constant.Kind == TypedConstantKind.Array)
        {
            var elementType = ((IArrayTypeSymbol)constant.Type!).ElementType
                .ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            return $"new {elementType}[] {{ {string.Join(", ", constant.Values.Select(RenderConstant))} }}";
        }
        return RenderPrimitive(constant.Value!);
    }

    private static string RenderPrimitive(object value)
    {
        return value switch
        {
            string text => SymbolDisplay.FormatLiteral(text, quote: true),
            char character => SymbolDisplay.FormatLiteral(character, quote: true),
            bool boolean => boolean ? "true" : "false",
            byte number => number.ToString(CultureInfo.InvariantCulture),
            sbyte number => number.ToString(CultureInfo.InvariantCulture),
            short number => number.ToString(CultureInfo.InvariantCulture),
            ushort number => number.ToString(CultureInfo.InvariantCulture),
            int number => number.ToString(CultureInfo.InvariantCulture),
            uint number => number.ToString(CultureInfo.InvariantCulture) + "U",
            long number => number.ToString(CultureInfo.InvariantCulture) + "L",
            ulong number => number.ToString(CultureInfo.InvariantCulture) + "UL",
            float number => number.ToString("R", CultureInfo.InvariantCulture) + "F",
            double number => number.ToString("R", CultureInfo.InvariantCulture) + "D",
            decimal number => number.ToString(CultureInfo.InvariantCulture) + "M",
            _ => throw new InvalidOperationException($"Unsupported validation attribute constant '{value.GetType().FullName}'."),
        };
    }

    private static string EscapeIdentifier(string identifier)
    {
        return SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None ? "@" + identifier : identifier;
    }
}
