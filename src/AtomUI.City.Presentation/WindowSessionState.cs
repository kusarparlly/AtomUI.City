namespace AtomUI.City.Presentation;

/// <summary>
/// Defines the supported window session state values.
/// </summary>
public enum WindowSessionState
{
    /// <summary>
    /// Represents the registered value.
    /// </summary>
    Registered,
    /// <summary>
    /// Represents the ready value.
    /// </summary>
    Ready,
    /// <summary>
    /// Represents the closing value.
    /// </summary>
    Closing,
    /// <summary>
    /// Represents the closed value.
    /// </summary>
    Closed,
    /// <summary>
    /// Represents the faulted value.
    /// </summary>
    Faulted,
}
