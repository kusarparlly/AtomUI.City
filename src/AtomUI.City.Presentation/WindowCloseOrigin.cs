namespace AtomUI.City.Presentation;

/// <summary>
/// Defines the supported window close origin values.
/// </summary>
public enum WindowCloseOrigin
{
    /// <summary>
    /// Represents the user value.
    /// </summary>
    User,
    /// <summary>
    /// Represents the application value.
    /// </summary>
    Application,
    /// <summary>
    /// Represents the operating system value.
    /// </summary>
    OperatingSystem,
}
