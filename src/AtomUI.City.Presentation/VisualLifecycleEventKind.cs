namespace AtomUI.City.Presentation;

/// <summary>
/// Defines the supported visual lifecycle event kind values.
/// </summary>
public enum VisualLifecycleEventKind
{
    /// <summary>
    /// Represents the attached value.
    /// </summary>
    Attached,
    /// <summary>
    /// Represents the detached value.
    /// </summary>
    Detached,
    /// <summary>
    /// Represents the loaded value.
    /// </summary>
    Loaded,
    /// <summary>
    /// Represents the unloaded value.
    /// </summary>
    Unloaded,
    /// <summary>
    /// Represents the focused value.
    /// </summary>
    Focused,
    /// <summary>
    /// Represents the unfocused value.
    /// </summary>
    Unfocused,
    /// <summary>
    /// Represents the visible value.
    /// </summary>
    Visible,
    /// <summary>
    /// Represents the hidden value.
    /// </summary>
    Hidden,
}
