namespace AtomUI.City.Testing;

/// <summary>
/// Defines the supported plugin test state values.
/// </summary>
public enum PluginTestState
{
    /// <summary>
    /// Represents the installed value.
    /// </summary>
    Installed,
    /// <summary>
    /// Represents the active value.
    /// </summary>
    Active,
    /// <summary>
    /// Represents the inactive value.
    /// </summary>
    Inactive,
    /// <summary>
    /// Represents the unloaded value.
    /// </summary>
    Unloaded,
}
