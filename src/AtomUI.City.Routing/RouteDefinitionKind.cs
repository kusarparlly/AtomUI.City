namespace AtomUI.City.Routing;

/// <summary>
/// Defines the supported route definition kind values.
/// </summary>
public enum RouteDefinitionKind
{
    /// <summary>
    /// Represents the route value.
    /// </summary>
    Route,
    /// <summary>
    /// Represents the layout value.
    /// </summary>
    Layout,
    /// <summary>
    /// Represents the index value.
    /// </summary>
    Index,
    /// <summary>
    /// Represents the group value.
    /// </summary>
    Group,
    /// <summary>
    /// Represents the redirect value.
    /// </summary>
    Redirect,
    /// <summary>
    /// Represents the extension point value.
    /// </summary>
    ExtensionPoint,
}
