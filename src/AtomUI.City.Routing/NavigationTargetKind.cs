namespace AtomUI.City.Routing;

/// <summary>
/// Defines the supported navigation target kind values.
/// </summary>
public enum NavigationTargetKind
{
    /// <summary>
    /// Represents the route reference value.
    /// </summary>
    RouteReference,
    /// <summary>
    /// Represents the path value.
    /// </summary>
    Path,
    /// <summary>
    /// Represents the deep link value.
    /// </summary>
    DeepLink,
    /// <summary>
    /// Represents the journal value.
    /// </summary>
    Journal,
}
