    /// Represents the route value.
    /// </summary>
    Route,
    /// <summary>
    /// Represents the activation value.
    /// </summary>
    Activation,
    /// <summary>
    /// Represents the plugin value.
    /// </summary>
    Plugin,
    /// <summary>
    /// Represents the manual value.
    /// </summary>
    Manual,
