namespace AtomUI.City.Security;

/// <summary>
/// Defines the supported account session mode values.
/// </summary>
public enum AccountSessionMode
{
    /// <summary>
    /// Represents the anonymous value.
    /// </summary>
    Anonymous = 0,
    /// <summary>
    /// Represents the online value.
    /// </summary>
    Online = 1,
    /// <summary>
    /// Represents the offline restricted value.
    /// </summary>
    OfflineRestricted = 2,
}
