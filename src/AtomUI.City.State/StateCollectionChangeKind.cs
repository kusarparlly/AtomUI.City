namespace AtomUI.City.State;

/// <summary>
/// Defines the supported state collection change kind values.
/// </summary>
public enum StateCollectionChangeKind
{
    /// <summary>
    /// Represents the added value.
    /// </summary>
    Added,
    /// <summary>
    /// Represents the updated value.
    /// </summary>
    Updated,
    /// <summary>
    /// Represents the removed value.
    /// </summary>
    Removed,
    /// <summary>
    /// Represents the cleared value.
    /// </summary>
    Cleared,
    /// <summary>
    /// Represents the reset value.
    /// </summary>
    Reset,
}
