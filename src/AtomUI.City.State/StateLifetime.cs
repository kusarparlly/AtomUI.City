namespace AtomUI.City.State;

/// <summary>
/// Defines the supported state lifetime values.
/// </summary>
public enum StateLifetime
{
    /// <summary>
    /// Represents the application value.
    /// </summary>
    Application,
    /// <summary>
    /// Represents the module value.
    /// </summary>
    Module,
    /// <summary>
    /// Represents the route value.
    /// </summary>
    Route,
    /// <summary>
    /// Represents the activation value.
    /// </summary>
    Activation,
    /// <summary>
    /// Represents the plugin value.
    /// </summary>
    Plugin,
}
