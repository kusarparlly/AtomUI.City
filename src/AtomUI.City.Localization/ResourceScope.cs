namespace AtomUI.City.Localization;

/// <summary>
/// Defines the supported resource scope values.
/// </summary>
public enum ResourceScope
{
    /// <summary>
    /// Represents the host value.
    /// </summary>
    Host,
    /// <summary>
    /// Represents the module value.
    /// </summary>
    Module,
    /// <summary>
    /// Represents the plugin value.
    /// </summary>
    Plugin,
    /// <summary>
    /// Represents the route value.
    /// </summary>
    Route,
    /// <summary>
    /// Represents the window value.
    /// </summary>
    Window,
    /// <summary>
    /// Represents the presentation value.
    /// </summary>
    Presentation,
}
