namespace AtomUI.City.Localization;

/// <summary>
/// Defines the supported localized resource kind values.
/// </summary>
public enum LocalizedResourceKind
{
    /// <summary>
    /// Represents the string value.
    /// </summary>
    String,
    /// <summary>
    /// Represents the formatted string value.
    /// </summary>
    FormattedString,
    /// <summary>
    /// Represents the pluralization value.
    /// </summary>
    Pluralization,
    /// <summary>
    /// Represents the resource object value.
    /// </summary>
    ResourceObject,
    /// <summary>
    /// Represents the flow direction value.
    /// </summary>
    FlowDirection,
    /// <summary>
    /// Represents the culture metadata value.
    /// </summary>
    CultureMetadata,
    /// <summary>
    /// Represents the validation message value.
    /// </summary>
    ValidationMessage,
    /// <summary>
    /// Represents the error message value.
    /// </summary>
    ErrorMessage,
    /// <summary>
    /// Represents the command text value.
    /// </summary>
    CommandText,
    /// <summary>
    /// Represents the route title value.
    /// </summary>
    RouteTitle,
}
